"""Builds data.js from the phrase files. All English."""
import json, os, re, sys
here = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, here)
from content_learn import CONTRACTIONS, VOCAB
from content_talk import LIFESAVERS, BUILDERS, QUESTIONS, EVERYDAY, STORY, REACT, MISTAKES
from contractions import contract
from expand import expand

ARROW = " → "  # full form, then short form; the voice pauses here


def topics(prefix, rows, natural=True):
    out = []
    for i, (title, tip, body) in enumerate(rows):
        items = []
        for line in body.strip().splitlines():
            line = line.strip()
            # The Contractions section shows the full form next to the short one, so it never goes through contract().
            if not natural:
                # Contractions section: the setting shows one form, the short one (on) or the full one (off)
                full, _, short = line.partition(" -> ")
                it = {"en": short or full}
                if short and full != short:
                    it["f"] = full
                items.append(it)
                continue
            else:
                assert "->" not in line, line
                line = contract(line)
            it = {"en": line}
            # The same phrase with no contractions, for the "Contractions: off" setting
            if natural and expand(line) != line:
                it["f"] = expand(line)
            items.append(it)
        out.append({"id": f"{prefix}{i + 1}", "title": title, "tip": tip, "items": items})
    return out


SECTIONS = [
    {"id": "contractions", "title": "Contractions", "sub": "The short forms people really use", "tag": "Learn", "topics": topics("k", CONTRACTIONS, natural=False)},
    {"id": "vocab", "title": "Basic vocabulary", "sub": "Everyday words, always inside a phrase", "tag": "Learn", "topics": topics("v", VOCAB)},
    {"id": "lifesavers", "title": "Lifesavers", "sub": "Get time, ask again, find the word", "tag": "Survive", "topics": topics("l", LIFESAVERS)},
    {"id": "builders", "title": "Sentence builders", "sub": "Patterns that work for everything", "tag": "Build", "topics": topics("b", BUILDERS)},
    {"id": "questions", "title": "Common questions", "sub": "The questions people ask, and real answers", "tag": "Talk", "topics": topics("q", QUESTIONS)},
    {"id": "everyday", "title": "Everyday life", "sub": "Food, work, weather, shopping and more", "tag": "Talk", "topics": topics("e", EVERYDAY)},
    {"id": "story", "title": "Telling a story", "sub": "The past, step by step", "tag": "Talk", "topics": topics("s", STORY)},
    {"id": "react", "title": "Reacting and giving opinions", "sub": "Agree, disagree and show interest", "tag": "Talk", "topics": topics("r", REACT)},
    {"id": "mistakes", "title": "Common mistakes", "sub": "Say it the right way", "tag": "Fix", "topics": topics("x", MISTAKES)},
]
for s in SECTIONS:
    s["group"] = "main"
    s["unit"] = "phrases"

# Checks: English only, no repeats, short enough to say from memory.
ids = [t["id"] for s in SECTIONS for t in s["topics"]]
assert len(ids) == len(set(ids))
all_text = [x for s in SECTIONS for t in s["topics"] for x in [t["title"], t["tip"]] + [i["en"] for i in t["items"]]] + [s["title"] + s["sub"] for s in SECTIONS]
spanish = [e for e in all_text if re.search(r"[áéíóúñüÁÉÍÓÚÑ¿¡]", e)]
assert not spanish, spanish
all_en = [i["en"] for s in SECTIONS for t in s["topics"] for i in t["items"]]
repeats = sorted({e for e in all_en if all_en.count(e) > 1})
assert not repeats, repeats
long = [e for e in all_en if len(e.split()) > 15]
assert not long, long
for s in SECTIONS:
    for t in s["topics"]:
        assert 10 <= len(t["items"]) <= 15, (t["title"], len(t["items"]))

with open(os.path.join(here, "data.js"), "w", encoding="utf-8") as f:
    f.write("/* Generated by build_data.py: edit the content files, not this one. */\n")
    f.write("window.SECTIONS = " + json.dumps(SECTIONS, ensure_ascii=False, separators=(",", ":")) + ";\n")
    f.write("window.SPOKEN = {};\nwindow.PRON = [];\n")
# index.html asks for data.js?v=<hash of the data>, so browsers never keep an old copy of the phrases
import hashlib
digest = hashlib.sha1(open(os.path.join(here, "data.js"), "rb").read()).hexdigest()[:8]
page = os.path.join(here, "index.html")
html = open(page, encoding="utf-8").read()
html = re.sub(r'<script src="data\.js(\?v=\w+)?"></script>', f'<script src="data.js?v={digest}"></script>', html)
open(page, "w", encoding="utf-8").write(html)
total = 0
for s in SECTIONS:
    n = sum(len(t["items"]) for t in s["topics"]); total += n
    print(f"  {s['title']}: {len(s['topics'])} topics, {n} phrases")
print(sum(len(s["topics"]) for s in SECTIONS), "topics,", total, "phrases")
